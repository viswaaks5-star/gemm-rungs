#!/usr/bin/env python3
"""Turn a ladder log into the README's results table.

    python3 tools/ladder_table.py sgemm/runs/<log>.txt                     # print the table
    python3 tools/ladder_table.py sgemm/runs/<log>.txt --readme README.md  # replace it in README

Reads the CSV lines bin/sgemm prints, plus the environment header at the top of the log. In
--readme mode the table replaces whatever sits between <!-- ladder:begin --> and
<!-- ladder:end -->, so the published numbers are always regenerated from a committed log and
never typed by hand. Standard library only.
"""

import argparse
import csv
import os
import re
import sys

BEGIN = "<!-- ladder:begin -->"
END = "<!-- ladder:end -->"


def parse_log(path):
    """Return (header, rows): the environment fields, and one dict per CSV data line."""
    header, rows, columns = {}, [], None
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.rstrip("\n")
            m = re.match(r"^(GIT_SHA|device|software|os)\s*:\s*(.*?)\s*$", line)
            if m and m.group(1) not in header:
                header[m.group(1)] = m.group(2)
            if line.startswith("CSV,"):
                fields = next(csv.reader([line]))[1:]
                if fields and fields[0] == "rung":
                    columns = fields
                elif columns:
                    rows.append(dict(zip(columns, fields)))
    return header, rows


def shape_label(m, n, k):
    return f"{m}³" if m == n == k else f"{m}×{n}×{k}"


def cell_text(row):
    gflops = float(row["gflops"])
    text = f"{gflops:,.0f}" if gflops >= 100 else f"{gflops:.1f}"
    pct = row.get("pct_cublas", "nan")
    if row["rung"].startswith("00_") or pct.lower() in ("nan", ""):
        return text
    return f"{text} ({float(pct):.1f}%)"


def make_table(header, rows, log_link):
    if not rows:
        raise SystemExit("no timed rows in the log (was it a --check-only run?)")
    shapes, rungs, cells = [], [], {}
    for r in rows:
        shape = (int(r["M"]), int(r["N"]), int(r["K"]))
        if shape not in shapes:
            shapes.append(shape)
        if r["rung"] not in rungs:
            rungs.append(r["rung"])
        cells[(r["rung"], shape)] = r

    clocks = [int(r["sm_lo"]) for r in rows] + [int(r["sm_hi"]) for r in rows]
    sha = header.get("GIT_SHA", "unknown")
    device = re.sub(r"\s*\(.*$", "", header.get("device", "unknown GPU"))
    meta = []
    date = re.match(r"(\d{4}-\d{2}-\d{2})", os.path.basename(log_link))
    if date:
        meta.append(date.group(1))
    clock = f"{min(clocks)} MHz" if min(clocks) == max(clocks) else f"{min(clocks)}–{max(clocks)} MHz"
    meta += [f"commit `{sha}`", device, f"SM clock {clock}", f"[raw log]({log_link})"]

    lines = [" · ".join(meta), ""]
    # The binary's own commit string is the truth; the file name (from scripts/ladder.sh) is a
    # second witness. Either one saying -dirty means no commit reproduces the run.
    if sha.endswith("-dirty") or sha == "unknown" or "-dirty" in os.path.basename(log_link):
        lines += ["> **Built from uncommitted code:** no commit reproduces this run.", ""]
    lines.append("| rung | " + " | ".join(shape_label(*s) for s in shapes) + " |")
    lines.append("|---|" + "---:|" * len(shapes))
    for rung in rungs:
        row = [cell_text(cells[(rung, s)]) if (rung, s) in cells else "—" for s in shapes]
        lines.append(f"| {rung} | " + " | ".join(row) + " |")
    lines += [
        "",
        "GFLOP/s, with % of cuBLAS in brackets; — means skipped or failed (the log says which). "
        "Generated by `tools/ladder_table.py` from the raw log; don't edit by hand.",
    ]
    return "\n".join(lines)


def splice(text, table, where="README"):
    b, e = text.find(BEGIN), text.find(END)
    if b < 0 or e < 0 or e < b:
        raise SystemExit(f"{where}: markers {BEGIN} ... {END} not found")
    return text[: b + len(BEGIN)] + "\n" + table + "\n" + text[e:]


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("log", help="a log written by bin/sgemm (scripts/ladder.sh saves them in sgemm/runs/)")
    p.add_argument("--readme", help="replace the table between the ladder markers in this file")
    args = p.parse_args(argv)

    header, rows = parse_log(args.log)
    if args.readme:
        link = os.path.relpath(args.log, os.path.dirname(os.path.abspath(args.readme)))
        table = make_table(header, rows, link.replace(os.sep, "/"))
        with open(args.readme, encoding="utf-8") as f:
            text = f.read()
        with open(args.readme, "w", encoding="utf-8") as f:
            f.write(splice(text, table, args.readme))
        print(f"{args.readme}: table regenerated from {args.log}")
    else:
        print(make_table(header, rows, args.log))
    return 0


if __name__ == "__main__":
    sys.exit(main())
